"""별첨1 응답코드 추출 TSV → C# 표 2개(본 앱 / KioskSim) 생성.

사용: python -I scripts/gen_van_code_table.py
입력: docs/payment_relay/spec/(별첨1)응답코드표_20240131_추출.tsv (페이지\t코드\t내용)
출력: src/KFTCTaxCAP/Protocol/Pos/KftcVanApprovalCodeTable.cs
      src/KFTCTaxCAP.KioskSim/Protocol/KftcVanApprovalCodeTable.cs
PRD §17.1(docs/payment_relay/PRD.md). 표를 고칠 때는 TSV를 고치고 이 스크립트를 다시 돌린다.
"""
import io, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "docs", "payment_relay", "spec", "(별첨1)응답코드표_20240131_추출.tsv")

rows = []
for line in io.open(TSV, encoding="utf-8"):
    if line.startswith("#") or not line.strip():
        continue
    page, code, text = line.rstrip("\n").split("\t")
    if not re.fullmatch(r"[0-9A-Z]{2}", code):
        raise SystemExit("bad code: " + code)
    rows.append((code, text))
codes = [c for c, _ in rows]
if len(codes) != len(set(codes)):
    raise SystemExit("duplicate code")

def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

entries = "\n".join(f"            [{lit(c)}] = {lit(t)}," for c, t in rows)
summary = f"""    /// <summary>
    /// KFTCVAN 통합전문 응답코드(2자리) → 내용. 902614 등 KFTCVAN 승인 응답은 <c>#7</c>에 <c>"V" + 이 코드</c>로 온다
    /// (PRD §17.1, §3.3.1-e — 정상은 <c>"000"</c>이며 <c>V00</c>은 쓰지 않는다). 출처:
    /// <c>docs/payment_relay/spec/(별첨1)응답코드표_20240131.pdf</c>({len(rows)}개). 문구는 원문 그대로(전화번호·오탈자 포함).
    /// <b>자동 생성 파일</b> — 손으로 고치지 말고 <c>…_추출.tsv</c>를 고친 뒤 <c>scripts/gen_van_code_table.py</c>를 다시 돌린다.
    /// </summary>"""

main = f"""// <auto-generated> scripts/gen_van_code_table.py 가 생성함 — 직접 수정 금지 </auto-generated>
using System;
using System.Collections.Generic;

namespace KFTCTaxCAP.Protocol.Pos;

{summary.replace('    ///', '///')}
internal static class KftcVanApprovalCodeTable
{{
    internal const int Count = {len(rows)};

    internal static readonly IReadOnlyDictionary<string, string> Entries = new Dictionary<string, string>(StringComparer.Ordinal)
    {{
{entries.replace('            [', '        [')}
    }};
}}
"""

sim = f"""// <auto-generated> scripts/gen_van_code_table.py 가 생성함 — 직접 수정 금지 </auto-generated>
using System;
using System.Collections.Generic;

namespace KFTCTaxCAP.KioskSim.Protocol
{{
{summary}
    /// <remarks>본 앱(<c>KFTCTaxCAP.Protocol.Pos.KftcVanApprovalCodeTable</c>)과 코드를 공유하지 않는다(P19-2) — 같은 TSV에서 따로 생성한다.</remarks>
    internal static class KftcVanApprovalCodeTable
    {{
        internal const int Count = {len(rows)};

        internal static readonly IReadOnlyDictionary<string, string> Entries = new Dictionary<string, string>(StringComparer.Ordinal)
        {{
{entries}
        }};
    }}
}}
"""

for path, text in [
    (os.path.join(ROOT, "src", "KFTCTaxCAP", "Protocol", "Pos", "KftcVanApprovalCodeTable.cs"), main),
    (os.path.join(ROOT, "src", "KFTCTaxCAP.KioskSim", "Protocol", "KftcVanApprovalCodeTable.cs"), sim),
]:
    with io.open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT), len(rows))
